export function nextLanguage(language: Language): Language {
  const index = languageOptions.findIndex((option) => option.code === language);
  return languageOptions[(index + 1) % languageOptions.length].code;
}

export function languageLabel(language: Language): string {
  return languageOptions.find((option) => option.code === language)?.label ?? "English";
}

export function languageShortLabel(language: Language): string {
  return languageOptions.find((option) => option.code === language)?.shortLabel ?? "EN";
}

export function localeForLanguage(language: Language): string {
  return localeByLanguage[language];
}

export function makeTranslator(language: Language): Translate {
  return (key, values = {}) => {
    const template = translations[language][key] ?? translations.en[key] ?? key;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template
    );
  };
}

